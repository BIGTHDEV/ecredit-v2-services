SET XACT_ABORT ON;
BEGIN TRANSACTION;

IF COL_LENGTH('dbo.EMAIL_REMINDER_CONFIGS', 'DAYS_BEFORE_EXPIRY') IS NULL
BEGIN
  ALTER TABLE dbo.EMAIL_REMINDER_CONFIGS
    ADD DAYS_BEFORE_EXPIRY INT NULL;
END;

IF OBJECT_ID('dbo.CK_EMAIL_REMINDER_CONFIGS_DAYS_BEFORE_EXPIRY', 'C') IS NULL
BEGIN
  EXEC sys.sp_executesql N'
    ALTER TABLE dbo.EMAIL_REMINDER_CONFIGS
      ADD CONSTRAINT CK_EMAIL_REMINDER_CONFIGS_DAYS_BEFORE_EXPIRY
        CHECK (DAYS_BEFORE_EXPIRY IS NULL OR DAYS_BEFORE_EXPIRY BETWEEN 1 AND 365);
  ';
END;

IF OBJECT_ID('dbo.CK_EMAIL_REMINDER_CONFIGS_TEMPLATE', 'C') IS NOT NULL
BEGIN
  ALTER TABLE dbo.EMAIL_REMINDER_CONFIGS
    DROP CONSTRAINT CK_EMAIL_REMINDER_CONFIGS_TEMPLATE;
END;

ALTER TABLE dbo.EMAIL_REMINDER_CONFIGS
  ADD CONSTRAINT CK_EMAIL_REMINDER_CONFIGS_TEMPLATE CHECK
    (TEMPLATE IN ('request-approval', 'request-backward', 'request-draft', 'request-final', 'request-temporary'));

EXEC sys.sp_executesql N'
  INSERT INTO dbo.EMAIL_REMINDER_CONFIGS
    (ID, TEMPLATE, INTERVAL_VALUE, INTERVAL_UNIT, DAYS_BEFORE_EXPIRY, CREATED_DATE, UPDATED_DATE,
     CREATED_BY, UPDATED_BY, ENABLED, SORTING)
  SELECT ''request-temporary'', ''request-temporary'', 1, ''days'', 30, GETDATE(), GETDATE(), 0, 0, 0, 5
  WHERE NOT EXISTS (
    SELECT 1 FROM dbo.EMAIL_REMINDER_CONFIGS WHERE TEMPLATE = ''request-temporary''
  );
';

COMMIT TRANSACTION;
