IF OBJECT_ID('NOTIFICATIONS', 'U') IS NULL
BEGIN
  CREATE TABLE NOTIFICATIONS (
    ID NVARCHAR(128) NOT NULL,
    RECIPIENT_EMAIL NVARCHAR(320) NOT NULL,
    RECIPIENT_NAME NVARCHAR(512) NULL,
    RECIPIENT_TYPE NVARCHAR(8) NOT NULL,
    REQUEST_ID NVARCHAR(128) NULL,
    REQUEST_NO NVARCHAR(128) NULL,
    EVENT_TYPE NVARCHAR(32) NOT NULL,
    TITLE NVARCHAR(512) NOT NULL,
    MESSAGE NVARCHAR(2048) NULL,
    TAB NVARCHAR(32) NOT NULL CONSTRAINT DF_NOTIFICATIONS_TAB DEFAULT 'customers',
    ACTOR_EMAIL NVARCHAR(320) NULL,
    ACTOR_NAME NVARCHAR(512) NULL,
    IS_READ BIT NOT NULL,
    READ_DATE DATETIME NULL,
    CREATED_DATE DATETIME NOT NULL,
    UPDATED_DATE DATETIME NOT NULL,
    CREATED_BY INT NOT NULL,
    UPDATED_BY INT NOT NULL,
    ENABLED BIT NOT NULL,
    SORTING INT NULL,
    CONSTRAINT PK_NOTIFICATIONS PRIMARY KEY (ID)
  );
END;

IF COL_LENGTH('NOTIFICATIONS', 'TAB') IS NULL
BEGIN
  ALTER TABLE NOTIFICATIONS
    ADD TAB NVARCHAR(32) NOT NULL CONSTRAINT DF_NOTIFICATIONS_TAB DEFAULT 'customers';
END;

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_NOTIFICATIONS_RECIPIENT' AND object_id = OBJECT_ID('NOTIFICATIONS'))
BEGIN
  CREATE INDEX IX_NOTIFICATIONS_RECIPIENT
    ON NOTIFICATIONS (RECIPIENT_EMAIL, ENABLED, IS_READ, CREATED_DATE DESC);
END;
