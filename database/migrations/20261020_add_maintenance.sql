SET XACT_ABORT ON;
BEGIN TRANSACTION;

IF OBJECT_ID('dbo.MAINTENANCE_CONFIG', 'U') IS NULL
BEGIN
  CREATE TABLE dbo.MAINTENANCE_CONFIG (
    ID VARCHAR(32) NOT NULL CONSTRAINT PK_MAINTENANCE_CONFIG PRIMARY KEY,
    ENABLED BIT NOT NULL CONSTRAINT DF_MAINTENANCE_CONFIG_ENABLED DEFAULT (0),
    MESSAGE VARCHAR(4000) NOT NULL,
    STARTS_AT DATETIMEOFFSET(3) NULL,
    ENDS_AT DATETIMEOFFSET(3) NULL,
    CREATED_DATE DATETIMEOFFSET(3) NOT NULL,
    UPDATED_DATE DATETIMEOFFSET(3) NOT NULL,
    CREATED_BY INT NOT NULL,
    UPDATED_BY INT NOT NULL,
    CONSTRAINT CK_MAINTENANCE_CONFIG_SINGLETON CHECK (ID = 'system'),
    CONSTRAINT CK_MAINTENANCE_CONFIG_INTERVAL CHECK (
      STARTS_AT IS NULL OR ENDS_AT IS NULL OR ENDS_AT > STARTS_AT
    ),
    CONSTRAINT CK_MAINTENANCE_CONFIG_ENABLED CHECK (
      ENABLED = 0 OR (
        LEN(LTRIM(RTRIM(MESSAGE))) > 0 AND STARTS_AT IS NOT NULL
        AND ENDS_AT IS NOT NULL AND ENDS_AT > STARTS_AT
      )
    )
  );
END;

IF NOT EXISTS (SELECT 1 FROM dbo.MAINTENANCE_CONFIG WITH (UPDLOCK, HOLDLOCK) WHERE ID = 'system')
BEGIN
  INSERT INTO dbo.MAINTENANCE_CONFIG
    (ID, ENABLED, MESSAGE, STARTS_AT, ENDS_AT, CREATED_DATE, UPDATED_DATE, CREATED_BY, UPDATED_BY)
  VALUES ('system', 0, N'', NULL, NULL, SYSUTCDATETIME(), SYSUTCDATETIME(), 0, 0);
END;

COMMIT TRANSACTION;
