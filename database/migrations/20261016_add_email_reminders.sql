SET XACT_ABORT ON;
BEGIN TRANSACTION;

IF OBJECT_ID('EMAIL_REMINDER_CONFIGS', 'U') IS NULL
BEGIN
  CREATE TABLE EMAIL_REMINDER_CONFIGS (
    ID VARCHAR(128) NOT NULL CONSTRAINT PK_EMAIL_REMINDER_CONFIGS PRIMARY KEY,
    TEMPLATE VARCHAR(128) NOT NULL CONSTRAINT UQ_EMAIL_REMINDER_CONFIGS_TEMPLATE UNIQUE,
    INTERVAL_VALUE INT NOT NULL,
    INTERVAL_UNIT VARCHAR(16) NOT NULL,
    CREATED_DATE DATETIME NOT NULL,
    UPDATED_DATE DATETIME NOT NULL,
    CREATED_BY INT NOT NULL,
    UPDATED_BY INT NOT NULL,
    ENABLED BIT NOT NULL CONSTRAINT DF_EMAIL_REMINDER_CONFIGS_ENABLED DEFAULT (1),
    SORTING INT NULL,
    CONSTRAINT CK_EMAIL_REMINDER_CONFIGS_TEMPLATE CHECK
      (TEMPLATE IN ('request-approval', 'request-backward', 'request-draft', 'request-final')),
    CONSTRAINT CK_EMAIL_REMINDER_CONFIGS_INTERVAL CHECK (INTERVAL_VALUE BETWEEN 1 AND 365),
    CONSTRAINT CK_EMAIL_REMINDER_CONFIGS_UNIT CHECK (INTERVAL_UNIT IN ('minutes', 'hours', 'days'))
  );
END;

INSERT INTO EMAIL_REMINDER_CONFIGS
  (ID, TEMPLATE, INTERVAL_VALUE, INTERVAL_UNIT, CREATED_DATE, UPDATED_DATE, CREATED_BY, UPDATED_BY, ENABLED, SORTING)
SELECT TEMPLATE, TEMPLATE, 1, 'days', GETDATE(), GETDATE(), 0, 0, 0, SORTING
FROM (VALUES
  ('request-approval', 1),
  ('request-backward', 2),
  ('request-draft', 3),
  ('request-final', 4)
) AS DEFAULTS(TEMPLATE, SORTING)
WHERE NOT EXISTS (SELECT 1 FROM EMAIL_REMINDER_CONFIGS AS C WHERE C.TEMPLATE = DEFAULTS.TEMPLATE);

IF OBJECT_ID('EMAIL_REMINDER_STATES', 'U') IS NULL
BEGIN
  CREATE TABLE EMAIL_REMINDER_STATES (
    ID VARCHAR(128) NOT NULL CONSTRAINT PK_EMAIL_REMINDER_STATES PRIMARY KEY,
    CONFIG_ID VARCHAR(128) NOT NULL,
    SOURCE_EMAIL_ID VARCHAR(128) NOT NULL,
    REQUEST_ID VARCHAR(128) NOT NULL,
    LAST_SENT_DATE DATETIME NULL,
    LAST_ATTEMPT_DATE DATETIME NULL,
    SENT_COUNT INT NOT NULL CONSTRAINT DF_EMAIL_REMINDER_STATES_COUNT DEFAULT (0),
    LAST_ERROR NVARCHAR(2048) NULL,
    CREATED_DATE DATETIME NOT NULL,
    UPDATED_DATE DATETIME NOT NULL,
    CREATED_BY INT NOT NULL,
    UPDATED_BY INT NOT NULL,
    ENABLED BIT NOT NULL CONSTRAINT DF_EMAIL_REMINDER_STATES_ENABLED DEFAULT (1),
    SORTING INT NULL,
    CONSTRAINT FK_EMAIL_REMINDER_STATES_CONFIG FOREIGN KEY (CONFIG_ID) REFERENCES EMAIL_REMINDER_CONFIGS(ID)
  );
END;

COMMIT TRANSACTION;
